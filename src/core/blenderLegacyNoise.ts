function smoothWeight(value: number): number {
  const square = f(value * value);
  return f(f(1 - f(3 * square)) + f(f(2 * square) * value));
}

function smoothWeightOpposite(value: number): number {
  const square = f(value * value);
  return f(f(1 - f(3 * square)) - f(f(2 * square) * value));
}

function hash2(x: number, y: number): number {
  return HASH[HASH[x & 255] + (y & 255)];
}

function gradientDot(index: number, x: number, y: number, z: number): number {
  const i = index * 3;
  return f(f(f(HASH_VECTORS[i] * x) + f(HASH_VECTORS[i + 1] * y)) + f(HASH_VECTORS[i + 2] * z));
}

/** Blender's original orgBlenderNoise(), with float rounding at C float assignments. */
function orgBlenderNoise(xInput: number, yInput: number, zInput: number): number {
  const x = f(xInput);
  const y = f(yInput);
  const z = f(zInput);
  const fx = f(Math.floor(x));
  const fy = f(Math.floor(y));
  const fz = f(Math.floor(z));
  const ox = f(x - fx);
  const oy = f(y - fy);
  const oz = f(z - fz);
  const ix = Math.trunc(fx);
  const iy = Math.trunc(fy);
  const iz = Math.trunc(fz);
  const jx = f(ox - 1);
  const jy = f(oy - 1);
  const jz = f(oz - 1);

  const cn1 = smoothWeight(ox);
  const cn2 = smoothWeight(oy);
  const cn3 = smoothWeight(oz);
  const cn4 = smoothWeightOpposite(jx);
  const cn5 = smoothWeightOpposite(jy);
  const cn6 = smoothWeightOpposite(jz);

  const b00 = hash2(ix, iy);
  const b10 = hash2(ix + 1, iy);
  const b01 = hash2(ix, iy + 1);
  const b11 = hash2(ix + 1, iy + 1);
  const b20 = iz & 255;
  const b21 = (iz + 1) & 255;

  let n = f(0.5);
  const add = (weight: number, hashIndex: number, dx: number, dy: number, dz: number) => {
    n = f(n + f(weight * gradientDot(HASH[hashIndex], dx, dy, dz)));
  };
  add(f(f(cn1 * cn2) * cn3), b20 + b00, ox, oy, oz);
  add(f(f(cn1 * cn2) * cn6), b21 + b00, ox, oy, jz);
  add(f(f(cn1 * cn5) * cn3), b20 + b01, ox, jy, oz);
  add(f(f(cn1 * cn5) * cn6), b21 + b01, ox, jy, jz);
  add(f(f(cn4 * cn2) * cn3), b20 + b10, jx, oy, oz);
  add(f(f(cn4 * cn2) * cn6), b21 + b10, jx, oy, jz);
  add(f(f(cn4 * cn5) * cn3), b20 + b11, jx, jy, oz);
  add(f(f(cn4 * cn5) * cn6), b21 + b11, jx, jy, jz);
  return n < 0 ? 0 : n > 1 ? 1 : n;
}

function legacyHNoise(periodInput: number, xInput: number, yInput: number, zInput: number): number {
  const period = f(periodInput);
  if (period === 0) return 0;
  const x = f(f(1 + f(xInput)) / period);
  const y = f(f(1 + f(yInput)) / period);
  const z = f(f(1 + f(zInput)) / period);
  return orgBlenderNoise(x, y, z);
}

function legacyTurbulence(period: number, x: number, y: number, z: number, depth: number): number {
  let sum = legacyHNoise(period, x, y, z);
  let amplitude = f(0.5);
  let divisor = f(1);
  let remaining = Math.trunc(depth);
  while (remaining > 0) {
    sum = f(sum + f(amplitude * legacyHNoise(f(period * amplitude), x, y, z)));
    divisor = f(divisor + amplitude);
    amplitude = f(amplitude * f(0.5));
    remaining -= 1;
  }
  return f(sum / divisor);
}

/**
 * Return Blender's legacy noise value centered around zero.
 *
 * period, phase, offset, and depth correspond to FMod_Noise's size, phase, offset,
 * and depth. Blender's modifier calls the legacy turbulence path with z=0.1 and applies
 * (noise - 0.5) * strength for replacement mode; strength and envelope are intentionally
 * left to the caller.
 */
export function legacyBlenderNoise(frame: number, m: LegacyBlenderNoiseSettings): number {
  const period = f(m.period);
  const phase = f(m.phase);
  const offset = f(m.offset ?? 0);
  const depth = Math.trunc(m.depth ?? 0);
  return f(legacyTurbulence(period, f(frame - offset), phase, f(0.1), depth) - f(0.5));
}
